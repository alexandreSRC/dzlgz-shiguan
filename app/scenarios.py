def scenario_of(year, mode=None):
    """存档年份 + 争霸类型 → 剧本名。取「开局年 ≤ year」里最晚的那一个。

    ★ **只在同一个争霸类型里查**。给了 `mode` 而这个类型在表里没有记录
      （比如「争霸模式」的完整表还没拿到）→ 返回空串，**不跨类型兜底**。
      为什么：同一年份在不同争霸类型下剧本名可以完全不同 ——
      前 771 年沙盒全局叫「平王东迁」、争霸模式叫「荆楚吴越」，
      拿沙盒的表去猜争霸模式，会把《荆楚吴越·争霸模式》写成《平王东迁·争霸模式》。
      认不出就让界面提示「手动指定目标谱牒」，比张冠李戴强。

    `mode` 为空或「未识别模式」（号段表里没有的槽）才在全表里找。
    """
    if year is None:
        return ""
    return scenario_match(year, mode)[0]


# 「向上容差」：year 落在两本之间的空洞、或比表内最早那本还早时，
# 允许向上取最近一本，但距离不得超过这个年数（否则宁可不认）。
DRIFT_TOL = 20


def scenario_match(year, mode=None):
    """存档年份 + 争霸类型 → `(剧本名, 开局年, 漂移, 余量)`。

    ★ 2026-09-22 修（B 批第 2 条）：原实现只有「开局年 ≤ year 里最晚的那本」一条规则。
      现补三件事，并把**实测事实**钉在这里，免得后面的人再从年份上打主意。

    **① 向上容差 `DRIFT_TOL`**
      `year` 落在「两本之间的空洞」或比表内最早那本还早时，老实现直接返回空串
      （界面只能提示「手动指定」）。实测漂移 0~6 年都可能出现，所以改为
      **允许向上取最近一本**，但距离必须 ≤ `DRIFT_TOL` 年，否则仍返回空。

    **② 漂移 / 余量诊断**
      `漂移 = year − 表内开局年`、`余量 = 下一本开局年 − 本本开局年`。
      判据：**`余量 − 漂移` 越小越危险**（越小说明"再多漂一点就翻到下一本去了"）。

    **③ ⚠️ 实测：真正的危险区是「秦汉段」，不是工作日志里写的战国段**
      沙盒全局相邻剧本间距 ——
        · 战国段 35 / 47 / 49 年（-361 / -326 / -279 / -230）→ **最安全**
        · 秦汉段却只有 **2 ~ 8 年**（-209 秦末起义 / -207 楚汉争霸 / -202 威加海内 / -181 诸吕之乱）
      实测 `Save_All_1 = -209`、漂移 **0**、余量仅 **2 年** ⇒ **只要漂移 3 年就会认成楚汉争霸**。
      而 2026-09-22 实测 `Save_All_100/2`（满天星斗）**已经漂移 6 年**。

    → **结论（重要）**：秦汉段这种「相邻 2 年」的剧本，**靠年份推理无法根治**：
      存档里**没有剧本名 / 编号字段**；`King_Stage_Record[0].Name`（「圣人阶段」）
      只有 **先民 / 礼法 / 方国 / 圣人** 四种，粒度太粗，区分不了剧本。
      所以本函数的定位是「**尽量猜 + 敢于承认不确定**」，而不是「一定能猜对」。
      真要根治只有两条路：游戏给出剧本标识（无），或**使用者手动指定目标谱牒**。
    """
    if year is None:
        return ("", None, None, None)
    if mode and mode != "未识别模式":
        rows = [r for r in SCENARIOS if r[0] == mode]
        if not rows:
            return ("", None, None, None)
    else:
        rows = list(SCENARIOS)
    rows = sorted(rows, key=lambda r: r[3])
    best = None
    for i, (_m, _g, name, start) in enumerate(rows):
        if start <= year and (best is None or start > best[1]):
            best = (name, start, i)
    if best is None:
        nxt = rows[0]
        if nxt[3] - year <= DRIFT_TOL:
            return (nxt[2], nxt[3], year - nxt[3], None)
        return ("", None, None, None)
    name, start, i = best
    margin = (rows[i + 1][3] - start) if i + 1 < len(rows) else None
    return (name, start, year - start, margin)


