def start_year_of(name):
    """剧本名 → 开局年（同名跨类型取最早）。查不到返回 None。"""
    return _NAME2YEAR.get(str(name or "").strip())


def match_name(text):
    """从一段文字里认出剧本名（用于「谱牒名 → 剧本」）。

    先精确包含剧本全名，再退到别名表。认不出返回空串。
    """
    s = str(text or "")
    if not s:
        return ""
    # 长的先匹配，避免「秦末起义」被「起义」这类短别名抢走
    for name in sorted(all_names(), key=len, reverse=True):
        if name in s:
            return name
    for alias, name in sorted(NAME_ALIASES.items(), key=lambda x: -len(x[0])):
        if alias in s:
            return name
    return ""


def label(year, mode=None):
    """给界面用的一行：`秦末起义 · 前 209`（认不出就返回空串）。"""
    name = scenario_of(year, mode)
    if not name:
        return ""
    y = start_year_of(name)
    if y is None:
        return name
    return f"{name} · {'前' if y < 0 else '公元'}{abs(y)}"


def book_name(year, mode=None):
    """存档年份 + 争霸类型 → **目标谱牒名**（`剧本名·争霸类型`）。

    使用者 2026-09-21 拍板：「谱牒名 = 剧本名·争霸类型」，例如
    《秦末起义·沙盒全局》。争霸类型认不出（号段表里没有）时只用剧本名。
    """
    name = scenario_of(year, mode)
    if not name:
        return ""
    if not mode or mode == "未识别模式":
        return name
    return f"{name}·{mode}"
