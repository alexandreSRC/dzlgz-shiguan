def buff_info(name, kind=None):
    """特质 → (中文名, (类型, 说明) | None)。名字存档自带（Buff_Name）。"""
    name = str(name)
    kind_zh = BUFF_KINDS.get(kind) if kind is not None else None
    hit = BUFF_HELP.get(name)
    if hit:
        tag, desc = hit
        return name, (tag, desc)
    if kind_zh:
        return name, (kind_zh, None)
    return name, None
