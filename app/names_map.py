def _info_by_name(name, table):
    hit = table.get(str(name))
    return (str(name), hit) if hit else (str(name), None)


def zhengce_info(code):
    """政策编号 → (名字, (类型, 效果) | None)。编号表优先，名字表兜底。"""
    try:
        code = int(str(code).strip())
    except (TypeError, ValueError):
        return str(code), None
    name = ZHENG_CE_CODES.get(code)
    if name:
        return _info_by_name(name, ZHENG_CE_INFO)
    return f"政策#{code}", None


